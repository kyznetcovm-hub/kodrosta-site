import {test} from 'node:test';
import assert from 'node:assert/strict';
import {translate,PostgresD1} from '../postgres.mjs';
test('SQL parameters do not alter literals, comments, or quoted identifiers',()=>{
  assert.equal(translate("SELECT '?' AS text, \"?\", a FROM t WHERE b=? -- ?\n AND c=?").text,
    "SELECT '?' AS text, \"?\", a FROM t WHERE b=$1 -- ?\n AND c=$2");
});
test('identity, conflict handling and rowid preserve SQLite operations',()=>{
  assert.match(translate('CREATE TABLE x (id INTEGER PRIMARY KEY AUTOINCREMENT, chat_id INTEGER)').text,/BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, chat_id BIGINT/);
  assert.match(translate('INSERT OR IGNORE INTO event_reminders(x) VALUES(?)').text,/VALUES\(\$1\) ON CONFLICT DO NOTHING$/);
  assert.match(translate('CREATE TABLE IF NOT EXISTS admission_requests (id TEXT PRIMARY KEY)').text,/rowid BIGINT GENERATED ALWAYS AS IDENTITY/);
  assert.match(translate('PRAGMA table_info(events)').text,/information_schema.columns/);
});
test('failed batch rolls back and releases its connection',async()=>{
  const log=[];const client={async query(sql){log.push(sql);},release(){log.push('release');}};
  const db=new PostgresD1({async connect(){return client;}});
  await assert.rejects(db.batch([{async execute(){throw new Error('failure');}}]),/failure/);
  assert.deepEqual(log,['BEGIN','ROLLBACK','release']);
});
