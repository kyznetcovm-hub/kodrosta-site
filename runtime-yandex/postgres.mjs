// Совместимый интерфейс D1 поверх PostgreSQL. Исходный Worker сохраняет свои запросы.
import pg from 'pg';
pg.types.setTypeParser(20, value => {
  const number = Number(value);
  if (!Number.isSafeInteger(number)) throw new Error('INTEGER exceeds safe JavaScript range');
  return number;
});
pg.types.setTypeParser(1700,value=>Number.isSafeInteger(Number(value))?Number(value):value);
const SERIAL_TABLES = new Set(['residents','touches','cron_runs','event_signups','sales','sales_plan_items','expenses','raffles']);

export function mapSql(sql, convert) {
  // Не трогаем литералы, имена в кавычках и комментарии, в том числе вопросительные знаки.
  const parts = sql.split(/('(?:''|[^'])*'|"(?:""|[^"])*"|`[^`]*`|--[^\n]*(?:\n|$)|\/\*[\s\S]*?\*\/)/g);
  return parts.map((part,index) => index % 2 ? part : convert(part)).join('');
}
export function translate(sql) {
  const pragma = sql.trim().match(/^PRAGMA\s+table_info\((\w+)\)\s*;?$/i);
  if (pragma) return { text: `SELECT ordinal_position-1 AS cid, column_name AS name,
    data_type AS type, CASE is_nullable WHEN 'NO' THEN 1 ELSE 0 END AS "notnull",
    column_default AS dflt_value, 0 AS pk FROM information_schema.columns
    WHERE table_schema=current_schema() AND table_name=$1 ORDER BY ordinal_position`, parameters:[pragma[1]] };
  const ignore = /^\s*INSERT\s+OR\s+IGNORE\s/i.test(sql);
  let text = mapSql(sql, code => code
    .replace(/INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT/gi,'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bINTEGER\b/gi,'BIGINT')
    .replace(/\bINSERT\s+OR\s+IGNORE\b/gi,'INSERT')
    .replace(/\bend(?=\s+TEXT\b)/gi,'"end"')
    .replace(/([,(]\s*)end(\s*[,])/gi,'$1"end"$2')
    .replace(/\bend(?=\s*=)/gi,'"end"')
    .replace(/(\b(?:events|excluded|e)\.)end\b/gi,'$1"end"')
    .replace(/\bAS\s+([A-Za-z_]\w*)/g,(match,name)=>/[a-z][A-Z]/.test(name)?'AS "'+name+'"':match)
    .replace(/CREATE TABLE IF NOT EXISTS admission_requests\s*\(/gi,
      'CREATE TABLE IF NOT EXISTS admission_requests (rowid BIGINT GENERATED ALWAYS AS IDENTITY,')
  );
  // PostgreSQL требует скобки вокруг CASE в определении индексного выражения.
  text = text.replace(/,\s*(CASE WHEN kind='access' THEN telegram_id ELSE 0 END)\)/gi,',($1))');
  if (ignore) text = text.trim().replace(/;$/,'') + ' ON CONFLICT DO NOTHING';
  const table = text.match(/^\s*INSERT\s+INTO\s+(\w+)/i)?.[1]?.toLowerCase();
  if (SERIAL_TABLES.has(table) && !/\bRETURNING\b/i.test(text)) text = text.trim().replace(/;$/,'') + ' RETURNING id';
  let index = 0;
  text = mapSql(text, code => code.replace(/\?/g, () => '$' + (++index)));
  return {text};
}
function result(data) {
  return { success:true, results:data.rows || [], meta:{changes:data.command === 'SELECT' ? 0 : data.rowCount || 0,
    last_row_id:data.rows?.[0]?.id ?? null} };
}
export class PostgresD1 {
  constructor(pool) { this.pool = pool; }
  prepare(sql) {
    const db = this;
    return { sql, values:[], bind(...values) { return {...this,values}; },
      async execute(client = db.pool) {
        const query = translate(sql);
        try { return result(await client.query(query.text,query.parameters || this.values)); }
        catch(error) { if (error.code === '42701') error.message = 'duplicate column: ' + error.message; throw error; }
      },
      async all() { return this.execute(); },
      async run() { return this.execute(); },
      async first(column) { const row = (await this.execute()).results[0] ?? null; return column && row ? row[column] : row; },
      async raw() { return (await this.execute()).results.map(row => Object.values(row)); }
    };
  }
  async batch(statements) {
    const client = await this.pool.connect();
    try { await client.query('BEGIN'); const results=[];
      for (const statement of statements) results.push(await statement.execute(client));
      await client.query('COMMIT'); return results;
    } catch(error) { await client.query('ROLLBACK'); throw error; }
    finally { client.release(); }
  }
  async exec(sql) { return this.pool.query(translate(sql).text); }
}
export function createDatabase(url) {
  const pool = new pg.Pool({connectionString:url,max:5,connectionTimeoutMillis:5000,statement_timeout:15000});
  return new PostgresD1(pool);
}
